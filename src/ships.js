export const SHIPS = [...LINERS, ...WARSHIPS];

/** Ship picker groups, in display order. */
export const CATEGORIES = [
  { id: "liner", label: "Ocean liners" },
  { id: "battleship", label: "Battleships" },
  { id: "cruiser", label: "Cruisers" },
  { id: "destroyer", label: "Destroyers" },
  { id: "carrier", label: "Aircraft carriers" },
  { id: "submarine", label: "Submarines" },
];

export const NAVIES = {
  Merchant: "Merchant",
  USN: "US Navy",
  RN: "Royal Navy",
  KM: "Kriegsmarine",
  RM: "Regia Marina",
  IJN: "Imperial Japanese Navy",
  MN: "Marine Nationale",
  VMF: "Soviet Navy",
};

/** Picker groups: each category's ships, grouped by navy in roster order. */
export function shipGroups(ships = SHIPS) {
  const order = Object.keys(NAVIES);
  return CATEGORIES.map((c) => ({
    ...c,
    ships: ships
      .filter((s) => s.category === c.id)
      .sort((a, b) => order.indexOf(a.navy) - order.indexOf(b.navy)),
  })).filter((g) => g.ships.length);
}

export function shipLabel(ship) {
  if (ship.category === "liner") return `${ship.name} (${ship.year})`;
  return `${ship.name} · ${NAVIES[ship.navy] ?? ship.navy} (${ship.year})`;
}

export function getShip(id) {
  return SHIPS.find((s) => s.id === id) ?? SHIPS[0];
}
