/**
 * Historical ocean liners and WWII warships — distinct proportions, not reskins.
 * Dimensions are stylized but relatively scaled (length units ≈ meters / 10).
 * `height` sets the silhouette scale; the main deck sits at 0.285 × height.
 * Compartments run bow → stern (index 0 = bow).
 * category: liner | battleship | cruiser | destroyer | carrier | submarine.
 * navy groups warships in the ship picker (see NAVIES).
 * Hull color = topside; antifoul red is applied below the waterline in the mesh.
 * Optional livery: sheerLine (thin line under the deck edge), bootTop (band at
 * the waterline), hospital (green band + red crosses), funnelBands (black
 * whistle bands, as fraction of funnel height), funnelBandColors (stripes
 * under the black top), dummyFunnels (indices that never smoked).
 *
 * Warship fields:
 *   turrets     [{ along, count, size, superfire?, raise?, facing?, barrel?, z? }] — main
 *               battery bow → stern. along 0 = bow, 1 = stern; count = barrels;
 *               size = gunhouse width; superfire raises it over its neighbour;
 *               raise overrides barbette height above the supporting deck;
 *               facing "fore" | "aft" (default by position); z = fraction of
 *               the half-beam off the centreline.
 *   secondary   { along: [...], count, size } — mounts in port/starboard pairs.
 *   torpedoes   [{ along, tubes }] — centreline launchers.
 *   deckGun     { along, size } — submarine deck gun.
 *   protection  0..1 armour belt / torpedo bulge; shrinks side breaches.
 *   strength    hull girder factor; scales the break-up thresholds (liner = 1).
 *   reserveBuoyancy  flood fraction absorbed before she settles (default 0.38).
 *   screws      propeller count.
 *   measure22   USN Measure 22 navy-blue band up to the lowest deck line.
 *   antifoulColor  paint below the waterline; deck "teak" | "steel", deckColor.
 */

